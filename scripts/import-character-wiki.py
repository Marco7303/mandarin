"""Build offline-ready character reference shards from the official Dong Chinese dump.
Usage: python3 scripts/import-character-wiki.py --input /path/to/dictionary_char_YYYY-MM-DD.jsonl
Omit --input to download the latest dump advertised by the official summary.
Only dictionary text is CC BY-SA 4.0; stroke graphics retain the Arphic Public License.
Historical image URLs are references only; third-party images are not redistributed.
"""
import argparse
import collections
import hashlib
import json
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = 'https://data.dong-chinese.com/dump/'

def text(value):
    return value.strip() if isinstance(value, str) else ''

def build(path):
    date = re.search(r'\d{4}-\d{2}-\d{2}', path.name)
    if not date:
        raise ValueError('Input filename must include the official dump date')
    version = 'dong-' + date[0] + '-v1'
    rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    source = {r['char']: r for r in rows if len(r.get('char') or '') == 1}
    details, strokes = collections.defaultdict(dict), collections.defaultdict(dict)
    verified = drawings = count = 0
    for char, row in sorted(source.items()):
        images = row.get('images') or []
        drawing = next((i['data'] for i in images if i.get('source') == 'makemeahanzi' and (i.get('data') or {}).get('strokes')), None)
        if not row.get('gloss') and not row.get('isVerified') and not drawing:
            continue
        checked = row.get('isVerified') is True
        bucket = format(ord(char) >> 8, 'x')
        components = []
        if checked:
            for part in row.get('components') or []:
                c = text(part.get('character'))
                ref = source.get(c, {})
                components.append(dict(character=c, roles=part.get('type') or ['unknown'], hint=text(part.get('hint')), meaning=text(ref.get('gloss'))))
        words = []
        for word in (row.get('statistics') or {}).get('topWords') or []:
            traditional = text(word.get('trad'))
            if char in traditional and traditional != char and text(word.get('gloss')) and traditional not in [w['traditional'] for w in words]:
                words.append(dict(traditional=traditional, meaning=text(word['gloss'])))
            if len(words) == 6:
                break
        history = []
        if checked:
            for image in images:
                url = image.get('url') or ''
                if url.startswith('https://data.dong-chinese.com/') and image.get('type') != 'Regular' and image.get('type') not in [x['type'] for x in history]:
                    history.append(dict(type=image.get('type'), era=text(image.get('era')), url=url, source=text(image.get('source'))))
        entry = dict(character=char, meaning=text(row.get('gloss')), verified=checked,
                     hint=text(row.get('hint')) if checked else '', originalMeaning=text(row.get('originalMeaning')) if checked else '',
                     components=components, words=words, history=history, hasStrokes=bool(drawing))
        details[bucket][char] = entry
        if drawing:
            # Keep upstream paths/medians unchanged; conversion only groups them into JSON shards.
            strokes[bucket][char] = dict(strokes=drawing['strokes'], medians=drawing.get('medians') or [])
            drawings += 1
        count += 1
        verified += checked
    out = ROOT / 'public/character-data' / version
    notice = 'Dictionary: Dong Chinese Character Wiki, CC BY-SA 4.0. Extracted, filtered and regrouped by Mori from ' + path.name + '.'
    for kind, shards in [('details', details), ('strokes', strokes)]:
        folder = out / kind
        folder.mkdir(parents=True, exist_ok=True)
        for bucket, chars in sorted(shards.items()):
            attribution = notice if kind == 'details' else 'Stroke graphics: Make Me a Hanzi; Copyright (C) 1999 Arphic Technology Co., Ltd. Arphic Public License. Paths unchanged; regrouped by Mori on 2026-11-11. No warranty. See /character-data/ARPHICPL.txt.'
            (folder / (bucket + '.json')).write_text(json.dumps(dict(notice=attribution, characters=chars), ensure_ascii=False, separators=(',', ':')) + '\n')
    manifest = dict(version=version, source=BASE + path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                    characters=count, verified=verified, strokeCharacters=drawings, details=sorted(details), strokes=sorted(strokes),
                    licence='CC BY-SA 4.0 (dictionary); Arphic Public License (stroke graphics)')
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    (ROOT / 'src/lib/character-data-version.ts').write_text('// Generated by scripts/import-character-wiki.py\nexport const CHARACTER_DATA_VERSION = ' + json.dumps(version) + ';\n')
    print(json.dumps(manifest, indent=2))
    print('Total JSON bytes:', sum(p.stat().st_size for p in out.rglob('*.json')))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=pathlib.Path)
    args = parser.parse_args()
    if not args.input:
        summary = json.load(urllib.request.urlopen(BASE + 'summary.json'))
        name = sorted(summary['charDumps'], reverse=True)[0]
        args.input = pathlib.Path('/tmp') / name
        urllib.request.urlretrieve(BASE + name, args.input)
    build(args.input)
